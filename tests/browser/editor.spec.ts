for (const viewport of [{ width: 1440, height: 1000 }, { width: 390, height: 844 }]) {
  test(`timeline overlay resizes and minimizes without resizing the scene at ${viewport.width}px`, async ({ page }) => {
    await page.setViewportSize(viewport);
    await page.goto('/#editor');
    await expect(page.getByRole('region', { name: 'Scene editor', exact: true })).toHaveAttribute('aria-busy', 'false');
    await page.getByRole('button', { name: 'Animations', exact: true }).click();
    await page.getByRole('button', { name: 'Add Drop to floor', exact: true }).click();
    await page.getByRole('button', { name: 'Close animations panel', exact: true }).click();
    await page.locator('.camera-switch').getByRole('button', { name: 'Camera view', exact: true }).click();
    await page.getByRole('button', { name: 'Drop to floor animation block', exact: true }).dblclick();
    const project = await page.evaluate(async () => { const path = '/src/core/store.ts'; return (await import(path)).studio.get().project; });
    const keys = page.getByRole('region', { name: 'Drop to floor keyframes', exact: true });
    const divider = page.getByRole('separator', { name: 'Resize timeline' });
    const scene = page.getByRole('region', { name: 'Scene editor', exact: true });
    const initialScene = (await scene.boundingBox())!;
    const frame = page.getByLabel('Camera frame', { exact: true });
    const initialFrame = (await frame.boundingBox())!;
    const handle = (await divider.boundingBox())!;
    await page.mouse.move(handle.x + handle.width / 2, handle.y + handle.height / 2);
    await page.mouse.down(); await page.mouse.move(handle.x + handle.width / 2, handle.y + handle.height / 2 + 60, { steps: 6 }); await page.mouse.up();
    await expect(divider).toHaveAttribute('aria-valuenow', '180');
    expect(await scene.boundingBox()).toEqual(initialScene);
    expect(await frame.boundingBox()).toEqual(initialFrame);
    await divider.press('ArrowUp');
    await expect(divider).toHaveAttribute('aria-valuenow', '200');
    await page.getByRole('button', { name: 'Minimize timeline' }).click();
    await expect(keys).toBeHidden();
    expect(await scene.boundingBox()).toEqual(initialScene);
    expect(await frame.boundingBox()).toEqual(initialFrame);
    await page.getByRole('button', { name: 'Play timeline', exact: true }).click();
    await expect(page.getByRole('button', { name: 'Pause timeline', exact: true })).toBeVisible();
    await page.getByRole('button', { name: 'Pause timeline', exact: true }).click();
    await page.getByRole('button', { name: 'Expand timeline' }).click();
    await expect(keys).toBeVisible();
    await expect(divider).toHaveAttribute('aria-valuenow', '200');
    await divider.press('End');
    await expect(divider).toHaveAttribute('aria-valuenow', String(viewport.height / 2));
    expect(await scene.boundingBox()).toEqual(initialScene);
    expect(await frame.boundingBox()).toEqual(initialFrame);
    await page.setViewportSize({ width: viewport.width, height: 600 });
    await expect(divider).toHaveAttribute('aria-valuenow', '300');
    expect((await scene.boundingBox())!.height).toBeGreaterThanOrEqual(290);
    expect(await page.evaluate(async () => { const path = '/src/core/store.ts'; return (await import(path)).studio.get().project; })).toEqual(project);
    expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBe(viewport.width);
  });
}


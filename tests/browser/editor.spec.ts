test('clicking a body part opens floating controls without resizing the scene', async ({ page }) => {
  await page.emulateMedia({ reducedMotion: 'reduce' });
  await page.goto('/#editor');
  const scene = page.getByRole('region', { name: 'Scene editor', exact: true });
  await expect(scene).toHaveAttribute('aria-busy', 'false');
  const before = (await scene.boundingBox())!;
  await page.locator('canvas').click({ position: { x: before.width / 2, y: before.height / 2 } });
  await expect(page.getByRole('complementary', { name: 'Pose controls' })).toBeVisible();
  await expect(page.getByRole('button', { name: 'Move model', exact: true })).toBeVisible();
  const after = (await scene.boundingBox())!;
  expect(after.width).toBe(before.width);
  expect(after.height).toBe(before.height);
  expect(after.width).toBe(page.viewportSize()!.width);
  await page.getByLabel('Selected joint', { exact: true }).selectOption('head');
  await page.screenshot({ path: 'test-results/floating-pose-controls.png', fullPage: true });
  await page.locator('canvas').click({ position: { x: 80, y: before.height * .7 } });
  await expect(page.getByRole('complementary', { name: 'Pose controls' })).toHaveCount(0);
  await expect(page.getByRole('button', { name: 'Move model', exact: true })).toHaveCount(0);
});

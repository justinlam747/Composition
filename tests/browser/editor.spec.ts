import { expect, test } from '@playwright/test';

test('Space toggles playback from editor controls without repeating or interrupting typing', async ({ page }) => {
  await page.goto('/#editor');
  await expect(page.getByRole('region', { name: 'Scene editor', exact: true })).toHaveAttribute('aria-busy', 'false');
  await page.getByRole('button', { name: 'Animate', exact: true }).click();
  await page.keyboard.down('Space');
  await expect(page.getByRole('button', { name: 'Pause timeline', exact: true })).toBeVisible();
  await page.keyboard.down('Space');
  await page.keyboard.up('Space');
  await expect.poll(async () => Number((await page.getByLabel('Current time').innerText()).split(' / ')[0])).toBeGreaterThan(.2);
  await page.keyboard.press('Space');
  await expect(page.getByRole('button', { name: 'Play timeline', exact: true })).toBeVisible();

  for (const control of [page.getByRole('button', { name: 'Play timeline', exact: true }), page.getByLabel('Timeline playhead')]) {
    await control.focus();
    await page.keyboard.press('Space');
    await expect(page.getByRole('button', { name: 'Pause timeline', exact: true })).toBeVisible();
    await page.keyboard.press('Space');
    await expect(page.getByRole('button', { name: 'Play timeline', exact: true })).toBeVisible();
  }
  await page.getByRole('button', { name: 'Minimize timeline' }).click();
  await page.keyboard.press('Space');
  await expect(page.getByRole('button', { name: 'Pause timeline', exact: true })).toBeVisible();
  await expect(page.getByRole('button', { name: 'Expand timeline' })).toBeVisible();
  await page.keyboard.press('Space');

  await page.getByRole('button', { name: 'Scene menu', exact: true }).click();
  await page.getByRole('button', { name: 'Rename project' }).click();
  const name = page.getByRole('textbox', { name: 'Project name' });
  await name.fill('Space'); await name.press('End'); await page.keyboard.press('Space');
  await expect(name).toHaveValue('Space ');
  await expect(page.getByRole('button', { name: 'Pause timeline', exact: true })).toHaveCount(0);
  await page.getByRole('button', { name: 'Cancel', exact: true }).click();
  await page.getByRole('button', { name: 'Output', exact: true }).click();
  await page.keyboard.press('Space');
  expect(await page.evaluate(async () => { const path = '/src/core/store.ts'; return (await import(path)).studio.get().playing; })).toBe(false);
});

